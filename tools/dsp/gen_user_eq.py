#!/usr/bin/env python3
# Generates src/T2AudioDspUserEq.h: fixed-point tables for the user tone
# controls (Parameters\BassDb, TrebleDb, ClarityDb) and the BS.1770
# K-weighting used by the autogain loudness meter. 48 kHz, Q28 biquads in the
# layout of T2DspBiquad: { b0, b1, b2, a1, a2 } with y = b.x - a1*y1 - a2*y2.
#
#   python3 tools/dsp/gen_user_eq.py src/T2AudioDspUserEq.h
#
# This file and its output are part of T2AudioPort (not derived from KAIT2EN).

import math, sys

Q = 28
RATE = 48000
MAX_DB = 12
BASS_HZ, TREBLE_HZ, CLARITY_HZ, CLARITY_Q = 150.0, 6000.0, 2500.0, 1.0


def shelf(kind, f0, db, fs=RATE):
    """Audio EQ Cookbook shelf, slope S = 1."""
    a = 10 ** (db / 40.0)
    w = 2 * math.pi * f0 / fs
    cw, sw = math.cos(w), math.sin(w)
    alpha = sw / 2 * math.sqrt((a + 1 / a) * (1 / 1.0 - 1) + 2)
    sa = 2 * math.sqrt(a) * alpha
    if kind == "low":
        b0 = a * ((a + 1) - (a - 1) * cw + sa)
        b1 = 2 * a * ((a - 1) - (a + 1) * cw)
        b2 = a * ((a + 1) - (a - 1) * cw - sa)
        a0 = (a + 1) + (a - 1) * cw + sa
        a1 = -2 * ((a - 1) + (a + 1) * cw)
        a2 = (a + 1) + (a - 1) * cw - sa
    else:
        b0 = a * ((a + 1) + (a - 1) * cw + sa)
        b1 = -2 * a * ((a - 1) + (a + 1) * cw)
        b2 = a * ((a + 1) + (a - 1) * cw - sa)
        a0 = (a + 1) - (a - 1) * cw + sa
        a1 = 2 * ((a - 1) - (a + 1) * cw)
        a2 = (a + 1) - (a - 1) * cw - sa
    return [b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0]


def peak(f0, q, db, fs=RATE):
    a = 10 ** (db / 40.0)
    w = 2 * math.pi * f0 / fs
    alpha = math.sin(w) / (2 * q)
    cw = math.cos(w)
    b0, b1, b2 = 1 + alpha * a, -2 * cw, 1 - alpha * a
    a0, a1, a2 = 1 + alpha / a, -2 * cw, 1 - alpha / a
    return [b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0]


# ITU-R BS.1770-4 K-weighting at 48 kHz (pre-filter shelf, then RLB high-pass).
KWEIGHT = [
    [1.53512485958697, -2.69169618940638, 1.19839281085285, -1.69065929318241, 0.73248077421585],
    [1.0, -2.0, 1.0, -1.99004745483398, 0.99007225036621],
]


def q(x):
    v = int(round(x * (1 << Q)))
    assert -(1 << 31) <= v < (1 << 31), x
    return v


def table(name, rows, comment):
    out = ["// %s" % comment, "static const int %s[%d][5] = {" % (name, len(rows))]
    for i, r in enumerate(rows):
        out.append("    { %s },   // %+d dB" % (", ".join(str(q(x)) for x in r), i - MAX_DB)
                   if len(rows) == 2 * MAX_DB + 1 else "    { %s }," % ", ".join(str(q(x)) for x in r))
    out.append("};")
    return out


def dtable(name, rows):
    out = ["static const double %s[%d][5] = {" % (name, len(rows))]
    for r in rows:
        out.append("    { %s }," % ", ".join(repr(x) for x in r))
    out.append("};")
    return out


def main(path):
    bass = [shelf("low", BASS_HZ, db) for db in range(-MAX_DB, MAX_DB + 1)]
    treble = [shelf("high", TREBLE_HZ, db) for db in range(-MAX_DB, MAX_DB + 1)]
    clarity = [peak(CLARITY_HZ, CLARITY_Q, db) for db in range(-MAX_DB, MAX_DB + 1)]
    L = ["#ifndef T2AUDIO_DSP_USER_EQ_H", "#define T2AUDIO_DSP_USER_EQ_H", "",
         "// Generated by tools/dsp/gen_user_eq.py - do not edit.",
         "// User tone controls, 48 kHz, Q%d, index = dB + %d (row %d is flat)." % (Q, MAX_DB, MAX_DB),
         "#define T2DSP_USER_EQ_MAX_DB %d" % MAX_DB, ""]
    L += table("g_T2DspBassShelf", bass, "Bass: low shelf %.0f Hz, slope 1." % BASS_HZ)
    L += table("g_T2DspTrebleShelf", treble, "Treble: high shelf %.0f Hz, slope 1." % TREBLE_HZ)
    L += table("g_T2DspClarityPeak", clarity, "Clarity: peaking EQ %.0f Hz, Q %.1f (voice presence)." % (CLARITY_HZ, CLARITY_Q))
    L += table("g_T2DspKWeight", KWEIGHT, "BS.1770 K-weighting (shelf, RLB high-pass), loudness meter only.")
    L += ["", "#ifdef T2AUDIO_DSP_REFERENCE"]
    L += dtable("g_T2DspRefBassShelf", bass)
    L += dtable("g_T2DspRefTrebleShelf", treble)
    L += dtable("g_T2DspRefClarityPeak", clarity)
    L += dtable("g_T2DspRefKWeight", KWEIGHT)
    L += ["#endif", "", "#endif", ""]
    open(path, "w", newline="\n").write("\n".join(L))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "src/T2AudioDspUserEq.h")
